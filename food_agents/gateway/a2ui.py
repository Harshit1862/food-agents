"""Builds A2UI messages (protocol v0.9) from the agents' structured results.

A2UI is declarative: instead of sending HTML, the server sends a flat list of components
("this is a ComparisonView, its children are these cards") and the React app draws them with
its own trusted catalog. Nothing here is generated by an LLM: the numbers come from the quotes,
the layout comes from this file.

Four message types are used:
    createSurface     start a new surface (a region of UI) with a catalog
    updateComponents  add or replace components of a surface (a flat list, linked by id)
    updateDataModel   change the data the components are bound to ({"path": "/order/stage"})
    deleteSurface     remove a surface
"""

import uuid

VERSION = "v0.9"
CATALOG_ID = "https://food-agents.local/a2ui/catalog/v1"  # our own catalog, see web/src/a2ui/catalog.jsx


def money(amount: float) -> str:
    return f"₹{int(round(amount))}"


class Surface:
    """Collects components for one surface and turns them into protocol messages."""

    def __init__(self, prefix: str = "s", surface_id: str | None = None) -> None:
        self.id = surface_id or f"{prefix}-{uuid.uuid4().hex[:6]}"
        self.components: list[dict] = []
        self.data: dict = {}

    def add(self, component_id: str, component: str, **props) -> str:
        """Add one component and return its id, so it can be listed as a child of another."""
        self.components.append({"id": component_id, "component": component, **props})
        return component_id

    def messages(self) -> list[dict]:
        out = [
            {"version": VERSION, "createSurface": {"surfaceId": self.id, "catalogId": CATALOG_ID}},
            {"version": VERSION, "updateComponents": {"surfaceId": self.id, "components": self.components}},
        ]
        if self.data:
            out.append({"version": VERSION, "updateDataModel": {"surfaceId": self.id, "path": "/", "value": self.data}})
        return out


def _price_props(option_or_order: dict) -> dict:
    return {
        "lines": [
            {"label": f"{int(l['qty'])} × {l['item']}", "amount": l["line_total"]}
            for l in option_or_order["lines"]
        ],
        "discount": option_or_order.get("discount", 0),
        "discountPct": option_or_order.get("discount_pct", 0),
        "deliveryFee": option_or_order["delivery_fee"],
        "total": option_or_order["total"],
    }


def _option_card(s: Surface, key: str, option: dict, best: bool = False, actionable: bool = True, score=None) -> str:
    children = []
    breakdown = option.get("eta_breakdown", {})
    children.append(
        s.add(
            f"{key}-eta",
            "ETABadge",
            minutes=option["eta_min"],
            prep=breakdown.get("prep_min", 0),
            rider=breakdown.get("rider_assign_min", 0),
            travel=breakdown.get("travel_min", 0),
        )
    )
    children.append(s.add(f"{key}-price", "PriceBreakdown", **_price_props(option)))
    if actionable:
        children.append(
            s.add(
                f"{key}-order",
                "ConfirmButton",
                label=f"Order from {option['platform_id'].title()}",
                total=option["total"],
                action={
                    "event": {
                        "name": "place_order",
                        "context": {"platform_id": option["platform_id"], "restaurant_id": option["restaurant_id"]},
                    }
                },
            )
        )
    return s.add(
        key,
        "RestaurantCard",
        platform=option["platform_id"],
        name=option["restaurant_name"],
        rating=option["rating"],
        score=score,
        best=best,
        violations=option.get("violations", []),
        children=children,
    )


def _order_line(order: dict) -> str:
    text = ", ".join(f"{i['qty']} × {i['name']}" for i in order["items"])
    limits = []
    if order.get("max_budget"):
        limits.append(f"under {money(order['max_budget'])}")
    if order.get("max_eta_min"):
        limits.append(f"within {round(order['max_eta_min'])} min")
    return text + (" · " + ", ".join(limits) if limits else "")


def recommendation(ui: dict) -> list[dict]:
    s = Surface("rec")
    cards = [
        _option_card(s, f"opt{n}", opt, best=(n == 0), score=opt.get("score"))
        for n, opt in enumerate(ui["options"])
    ]
    root_children = [
        s.add("title", "Text", text=_order_line(ui["order"]), variant="h3"),
        s.add("compare", "ComparisonView", children=cards),
    ]
    if ui["not_eligible"]:
        blocked = [
            _option_card(s, f"no{n}", opt, actionable=False) for n, opt in enumerate(ui["not_eligible"])
        ]
        root_children.append(s.add("blocked-title", "Text", text="Outside your limits", variant="caption"))
        root_children.append(s.add("blocked", "ComparisonView", children=blocked, muted=True))
    for n, note in enumerate(ui.get("notes", [])):
        root_children.append(s.add(f"note{n}", "Text", text=note, variant="caption"))
    s.add("root", "Column", children=root_children)
    return s.messages()


def question(ui: dict) -> list[dict]:
    s = Surface("ask")
    kids = []
    for n, entry in enumerate(ui["needs_input"]):
        for m, issue in enumerate(entry["issues"]):
            if issue["problem"] == "ambiguous":
                prompt = f"{entry['restaurant_name']} has several matches for '{issue['item']}'"
                choices = issue["options"]
            elif issue["problem"] == "unavailable":
                prompt = f"{issue['item']} is unavailable at {entry['restaurant_name']}"
                choices = issue["alternatives"]
            else:
                continue
            key = f"q{n}-{m}"
            kids.append(s.add(f"{key}-text", "Text", text=prompt, variant="body"))
            buttons = [
                s.add(
                    f"{key}-b{c}",
                    "Button",
                    label=choice,
                    action={"event": {"name": "say", "context": {"text": choice}}},
                )
                for c, choice in enumerate(choices)
            ]
            kids.append(s.add(f"{key}-row", "Row", children=buttons))
    s.add("root", "Column", children=kids)
    return s.messages()


def no_match(ui: dict) -> list[dict]:
    s = Surface("near")
    cards = [_option_card(s, f"c{n}", opt, actionable=False) for n, opt in enumerate(ui["closest"][:3])]
    s.add(
        "root",
        "Column",
        children=[
            s.add("cards", "ComparisonView", children=cards, muted=True),
            s.add("hint", "Text", text="Say which limit to relax, for example “make the budget 900”.", variant="caption"),
        ],
    )
    return s.messages()


def receipt(ui: dict) -> list[dict]:
    order = ui["order"]
    s = Surface("done")
    s.add(
        "root",
        "Column",
        children=[
            s.add("title", "Text", text="Your receipt", variant="h3"),
            s.add(
                "sub",
                "Text",
                text=f"{order['restaurant_name']} via {order['platform_id'].title()} · order {order['order_id']}",
                variant="caption",
            ),
            s.add("bill", "PriceBreakdown", **_price_props(order)),
        ],
    )
    return s.messages()


def tracker(stage: dict, surface_id: str | None = None, create: bool | None = None) -> list[dict]:
    """The live order tracker. The first stage creates the surface; later stages only
    change the data model, and the components bound to it redraw themselves."""
    sid = surface_id or f"track-{stage['order_id']}"
    order = {
        "order_id": stage["order_id"],
        "stage": stage["stage"],
        "text": stage["text"],
        "minutes_left": stage["minutes_left"],
    }
    if create is None:
        create = stage["stage"] == "confirmed"
    if not create:
        return [{"version": VERSION, "updateDataModel": {"surfaceId": sid, "path": "/order", "value": order}}]

    s = Surface(surface_id=sid)
    s.add(
        "root",
        "OrderTracker",
        restaurant=stage["restaurant_name"],
        platform=stage["platform_id"],
        orderId={"path": "/order/order_id"},
        stage={"path": "/order/stage"},
        text={"path": "/order/text"},
        minutesLeft={"path": "/order/minutes_left"},
    )
    s.data = {"order": order}
    return s.messages()


def menu(restaurant_name: str, items: list[dict]) -> list[dict]:
    """A plain menu (no Add buttons), used by the 'Talk to an agent' page for a restaurant's own menu."""
    s = Surface("menu")
    kids = [
        s.add(
            f"item{n}",
            "MenuItem",
            name=item["name"],
            price=item["base_price"],
            veg=item["is_veg"],
            available=item["available"],
            tags=item.get("tags", []),
        )
        for n, item in enumerate(items)
    ]
    s.add(
        "root",
        "Column",
        children=[s.add("title", "Text", text=restaurant_name, variant="h3"), s.add("list", "Column", children=kids)],
    )
    return s.messages()


def _event(name: str, context: dict) -> dict:
    return {"event": {"name": name, "context": context}}


def restaurants(block: dict) -> list[dict]:
    """The restaurant list of one platform. Tapping a tile asks for that restaurant's menu."""
    s = Surface("rest")
    tiles = [
        s.add(
            f"r{n}",
            "RestaurantTile",
            platform=block["platform_id"],
            name=r["name"],
            cuisine=r["cuisine"],
            rating=r["rating"],
            etaMin=r["eta_min"],
            deliveryFee=r["delivery_fee"],
            discountPct=r["discount_pct"],
            open=r["is_online"],
            action=_event("show_menu", {"platform_id": block["platform_id"], "restaurant_id": r["restaurant_id"]}),
            echo=f"Menu: {r['name']}",
        )
        for n, r in enumerate(block["restaurants"])
    ]
    title = f"Restaurants on {block['platform_name']}" + (f" · {block['filter']}" if block.get("filter") else "")
    s.add(
        "root",
        "Column",
        children=[
            s.add("title", "Text", text=title, variant="h3"),
            s.add("hint", "Text", text="Tap a restaurant to see its menu.", variant="caption"),
            s.add("list", "ComparisonView", children=tiles),
        ],
    )
    return s.messages()


def _menu_row(s: Surface, row: dict, platform_id: str, restaurant_id: str, open_: bool = True) -> str:
    """One dish with Add / minus / plus. Its counter is bound to /qty/<key>, so a cart change
    only has to update the data model for every menu on screen to redraw."""
    item, key = row["item"], row["key"]
    context = {"platform_id": platform_id, "restaurant_id": restaurant_id, "item": item["name"]}
    return s.add(
        f"row-{key}",
        "MenuItem",
        name=item["name"],
        price=item["price"],
        veg=item["is_veg"],
        available=bool(item["available"] and open_),
        tags=item.get("tags", []),
        qty={"path": f"/qty/{key}"},
        addAction=_event("cart_add", {**context, "delta": 1}),
        removeAction=_event("cart_add", {**context, "delta": -1}),
    )


def menu_block(block: dict) -> list[dict]:
    """A restaurant's menu at one platform's prices, with Add buttons."""
    s = Surface(surface_id=block["sid"])
    rows = [_menu_row(s, row, block["platform_id"], block["restaurant_id"], block["is_online"]) for row in block["rows"]]
    facts = [
        block["cuisine"],
        f"★ {block['rating']:.1f}",
        f"about {round(block['eta_min'])} min",
        f"delivery {money(block['delivery_fee'])}",
    ]
    if block["discount_pct"]:
        facts.append(f"{round(block['discount_pct'])}% off")
    if not block["is_online"]:
        facts.append("closed right now")
    kids = [
        s.add("title", "Text", text=f"{block['restaurant_name']} on {block['platform_name']}", variant="h3"),
        s.add("facts", "Text", text=" · ".join(facts), variant="caption"),
    ]
    if block.get("filters"):
        kids.append(s.add("filters", "Text", text=block["filters"], variant="caption"))
    kids.append(s.add("list", "Column", children=rows))
    s.add("root", "Column", children=kids)
    s.data = {"qty": block["qty"]}
    return s.messages()


def dishes(block: dict) -> list[dict]:
    """Search results: the restaurants that serve a dish, each with its matching dishes."""
    s = Surface(surface_id=block["sid"])
    cards = []
    for n, group in enumerate(block["groups"]):
        rows = [_menu_row(s, row, group["platform_id"], group["restaurant_id"]) for row in group["rows"]]
        cards.append(
            s.add(
                f"g{n}",
                "RestaurantCard",
                platform=group["platform_id"],
                name=group["restaurant_name"],
                rating=group["rating"],
                best=False,
                violations=[],
                children=rows,
            )
        )
    s.add(
        "root",
        "Column",
        children=[
            s.add("title", "Text", text=f"“{block['query']}”", variant="h3"),
            s.add("cards", "ComparisonView", children=cards),
        ],
    )
    s.data = {"qty": block["qty"]}
    return s.messages()


def cart(block: dict) -> list[dict]:
    """The cart, priced by the platform. One fixed surface id: a newer cart replaces the older one."""
    s = Surface(surface_id="cart")
    option = block.get("option")
    place = f"{block['restaurant_name']} via {block['platform_id'].title()}"
    kids = [s.add("title", "Text", text="Your cart", variant="h3"), s.add("sub", "Text", text=place, variant="caption")]

    if option is None:
        kids.append(s.add("problem", "Text", text=block.get("problem") or "This cart can't be priced right now.", variant="body"))
        kids.append(s.add("clear", "Button", label="Clear cart", action=_event("clear_cart", {})))
        s.add("root", "Column", children=kids)
        return s.messages()

    lines = []
    for n, line in enumerate(option["lines"]):
        context = {"platform_id": block["platform_id"], "restaurant_id": block["restaurant_id"], "item": line["item"]}
        lines.append(
            s.add(
                f"line{n}",
                "CartLine",
                name=line["item"],
                qty=line["qty"],
                unitPrice=line["unit_price"],
                lineTotal=line["line_total"],
                addAction=_event("cart_add", {**context, "delta": 1}),
                removeAction=_event("cart_add", {**context, "delta": -1}),
            )
        )
    kids.append(s.add("lines", "Column", children=lines))
    breakdown = option["eta_breakdown"]
    kids.append(
        s.add("eta", "ETABadge", minutes=option["eta_min"], prep=breakdown["prep_min"], rider=breakdown["rider_assign_min"], travel=breakdown["travel_min"])
    )
    price = _price_props(option)
    price["lines"] = []  # the dishes are listed above, with their own totals
    kids.append(s.add("price", "PriceBreakdown", **price))
    kids.append(
        s.add(
            "actions",
            "Row",
            children=[
                s.add("place", "ConfirmButton", label="Place order", total=option["total"], action=_event("checkout", {})),
                s.add("clear", "Button", label="Clear cart", action=_event("clear_cart", {})),
            ],
        )
    )
    s.add("root", "Column", children=kids)
    return s.messages()


def choices(block: dict) -> list[dict]:
    """Tappable answers to a question the assistant asked."""
    s = Surface("ask")
    buttons = [
        s.add(f"c{n}", "Button", label=c["label"], action={"event": c["action"]}) for n, c in enumerate(block["choices"])
    ]
    s.add("root", "Row", children=buttons)
    return s.messages()


def for_blocks(blocks: list[dict], sync: list[dict] | None = None) -> list[dict] | None:
    """All A2UI messages for one reply of the client agent, or None when it is plain text.
    `blocks` are the agent's structured results; `sync` updates menus already on screen."""
    builders = {
        "restaurants": restaurants,
        "menu": menu_block,
        "dishes": dishes,
        "cart": cart,
        "choices": choices,
        "recommendation": recommendation,
        "question": question,
        "no_match": no_match,
        "receipt": receipt,
    }
    messages: list[dict] = []
    for block in blocks:
        if block["kind"] in builders:
            messages += builders[block["kind"]](block)
        elif block["kind"] == "status":
            messages += tracker(block["stage"], surface_id=f"status-{uuid.uuid4().hex[:6]}", create=True)
    for entry in sync or []:
        messages.append({"version": VERSION, "updateDataModel": {"surfaceId": entry["sid"], "path": "/qty", "value": entry["qty"]}})
    return messages or None